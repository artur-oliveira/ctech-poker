// Fetches the Noto emoji art for every reaction glyph into public/emoji/ and
// rewrites src/components/ui/emojiManifest.ts. Run by hand (output is committed),
// like og:capture. Animated Noto (CC BY 4.0) is re-encoded to 160px WebP and paired with the flat Noto SVG
// (Apache 2.0) as its still; glyphs Google never animated ship the flat SVG for both.
// Usage: node scripts/fetch-noto-emoji.mjs
import {existsSync} from 'node:fs';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import sharp from 'sharp';

const BASE = 'https://fonts.gstatic.com/s/e/notoemoji/latest';
const SIZE = 160;
const src = await readFile(new URL('../src/lib/reactions.ts', import.meta.url), 'utf8');
const glyphs = [...new Set([...src.matchAll(/glyph: '([^']+)'/g)].map(m => m[1]))].filter(g => g !== '🟠');
const out = new URL('../public/emoji/', import.meta.url);
await mkdir(out, {recursive: true});

const get = async url => {
  const res = await fetch(url);
  return res.ok ? Buffer.from(await res.arrayBuffer()) : null;
};

// Stills are the ORIGINAL static Noto (flat SVG), not frames of the animation: a frame is often a
// meaningless mid-motion pose (the yawn's hand-on-face). Exception: the flat cucumber is the sliced one,
// the animation's first frame is the whole cucumber, so that glyph keeps a frame still.
const FRAME_STILL = new Set(['1f952']);

const manifest = {};
for (const glyph of glyphs) {
  const key = Array.from(glyph).map(c => c.codePointAt(0).toString(16)).join('-'); // matches codepointFor
  const noto = Array.from(glyph).map(c => c.codePointAt(0).toString(16)).filter(c => c !== 'fe0f').join('_');
  const animPath = new URL(`${key}.webp`, out);
  // An already re-encoded animation is reused (the encode is slow); delete the file to refresh it.
  let webp = existsSync(animPath) ? await readFile(animPath) : null;
  if (!webp) {
    const anim = await get(`${BASE}/${noto}/512.webp`);
    if (anim) webp = await sharp(anim, {animated: true}).resize(SIZE, SIZE).webp({quality: 78, effort: 6}).toBuffer();
    if (webp) await writeFile(animPath, webp);
  }
  if (webp) {
    const flat = FRAME_STILL.has(key) ? null : await get(`${BASE}/${noto}/emoji.svg`);
    if (flat) {
      await writeFile(new URL(`${key}.svg`, out), flat);
      manifest[key] = 'anim';
    } else {
      await writeFile(new URL(`${key}-still.webp`, out), await sharp(webp, {page: 0}).resize(96, 96).webp({quality: 82, effort: 6}).toBuffer());
      manifest[key] = 'anim-frame';
    }
  } else {
    const svg = await get(`${BASE}/${noto}/emoji.svg`);
    if (!svg) throw new Error(`no Noto art for ${glyph} (${noto})`);
    await writeFile(new URL(`${key}.svg`, out), svg);
    manifest[key] = 'svg';
  }
  console.log(glyph, key, manifest[key]);
}
const body = Object.entries(manifest).map(([k, v]) => `  '${k}': '${v}'`).join(',\n');
await writeFile(new URL('../src/components/ui/emojiManifest.ts', import.meta.url),
  `// Generated by scripts/fetch-noto-emoji.mjs — do not edit.\nexport const NOTO_EMOJI: Record<string, 'anim' | 'anim-frame' | 'svg'> = {\n${body}\n};\n`);
