// Command gen builds the deterministic preflop equity table. It uses PCG
// sampling independently of the runtime Monte Carlo implementation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math/rand/v2"
	"os"
	"sync"

	"gopkg.aoctech.app/poker/api/internal/engine/equity/preflop"
	"gopkg.aoctech.app/poker/api/internal/engine/handeval"
)

// Every possible split among hero plus up to eight opponents divides 2520.
// Integer accumulation keeps generation independent of floating-point sums.
const shareUnits uint64 = 2520

func estimateClass(class, samples int) [preflop.MaxOpponents]float32 {
	hole := preflop.Hole(class)
	h1, h2 := handeval.CardID(hole[0]), handeval.CardID(hole[1])
	var pool [50]uint8
	n := 0
	for id := uint8(0); id < 52; id++ {
		if id != h1 && id != h2 {
			pool[n] = id
			n++
		}
	}
	rng := rand.New(rand.NewPCG(preflop.GeneratorSeed, uint64(class)))
	var totals [preflop.MaxOpponents]uint64
	for range samples {
		var board handeval.BoardState
		for i := 0; i < 5; i++ {
			j := i + rng.IntN(len(pool)-i)
			pool[i], pool[j] = pool[j], pool[i]
			board.AddCardID(pool[i])
		}
		hero := board.Eval2IDs(h1, h2)
		tied := uint64(1)
		for opponent := range preflop.MaxOpponents {
			offset := 5 + opponent*2
			for i := offset; i < offset+2; i++ {
				j := i + rng.IntN(len(pool)-i)
				pool[i], pool[j] = pool[j], pool[i]
			}
			score := board.Eval2IDs(pool[offset], pool[offset+1])
			if score > hero {
				break
			}
			if score == hero {
				tied++
			}
			totals[opponent] += shareUnits / tied
		}
	}
	var out [preflop.MaxOpponents]float32
	for i, v := range totals {
		out[i] = float32(float64(v) / float64(uint64(samples)*shareUnits))
	}
	return out
}

func generate(samples, workers int) [preflop.Classes][preflop.MaxOpponents]float32 {
	var values [preflop.Classes][preflop.MaxOpponents]float32
	jobs := make(chan int, preflop.Classes)
	for class := range preflop.Classes {
		jobs <- class
	}
	close(jobs)
	completed := make(chan struct{}, preflop.Classes)
	var wg sync.WaitGroup
	for range workers {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for class := range jobs {
				values[class] = estimateClass(class, samples)
				completed <- struct{}{}
			}
		}()
	}
	go func() { wg.Wait(); close(completed) }()
	count := 0
	for range completed {
		count++
		if count%16 == 0 || count == preflop.Classes {
			fmt.Fprintf(os.Stderr, "preflop: generated %d/%d classes\n", count, preflop.Classes)
		}
	}
	return values
}

func main() {
	output := flag.String("o", "table_generated.go", "generated Go source")
	samples := flag.Int("samples", preflop.DefaultSamples, "samples per starting-hand class")
	workers := flag.Int("workers", 4, "parallel class generators")
	flag.Parse()
	if *samples < 1 || uint64(*samples) > (^uint64(0))/shareUnits || *workers < 1 || *workers > preflop.Classes {
		fmt.Fprintln(os.Stderr, "preflop: invalid samples or workers")
		os.Exit(1)
	}
	values := generate(*samples, *workers)
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go generate ./internal/engine/equity/preflop; DO NOT EDIT.")
	fmt.Fprintf(&b, "// PCG seed %#x, %d samples per class; expected pot share vs uniform random hands.\n", preflop.GeneratorSeed, *samples)
	fmt.Fprintln(&b, "package preflop")
	fmt.Fprintf(&b, "const GeneratedSamples = %d\n", *samples)
	fmt.Fprintln(&b, "var equities = [Classes][MaxOpponents]float32{")
	for _, row := range values {
		fmt.Fprint(&b, "{")
		for _, v := range row {
			fmt.Fprintf(&b, "%.9g,", v)
		}
		fmt.Fprintln(&b, "},")
	}
	fmt.Fprintln(&b, "}")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, src, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("preflop: wrote %s (%d values, %d samples/class)\n", *output, preflop.Classes*preflop.MaxOpponents, *samples)
}
