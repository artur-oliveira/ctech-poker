// Run from mobile/. Copies artwork from the web client; no independent icon set.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const require = createRequire(path.resolve('../ui/package.json'));
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const lucide = require('lucide-react');
const icons = ['Plus','Camera','ArrowUp','Bookmark','BookmarkPlus','LayoutGrid','MessageCircle','Check','CircleCheck','ChevronRight','CloudOff','Copy','MailOpen','Pencil','NotebookPen','SmilePlus','Trophy','ListFilter','SkipBack','Flag','Folder','CircleHelp','Hourglass','History','Share2','KeyRound','Lock','LogIn','LogOut','Mail','Mic','EllipsisVertical','Coins','Pause','Users','UserRound','UserRoundPlus','Play','ReceiptText','Gift','RefreshCw','Send','StepForward','StepBack','ShoppingBag','Layers','ShieldCheck','Award','ArrowLeft','ArrowRight','Info','Star','X','SlidersHorizontal','Activity','Search','Wallet','ChevronDown'];
fs.mkdirSync('assets/icons', {recursive:true});
for (const name of icons) {
  const svg = renderToStaticMarkup(React.createElement(lucide[name], {size:24, strokeWidth:1.8}));
  fs.writeFileSync(`assets/icons/${name}.svg`, svg);
}
fs.copyFileSync('../ui/node_modules/lucide-react/LICENSE','assets/icons/LICENSE');
const dart = `// Generated by tool/sync-web-assets.mjs from the web client's lucide-react.\nabstract final class PokerIcons {\n${icons.map(n=>`  static const ${n[0].toLowerCase()+n.slice(1)} = '${n}';`).join('\n')}\n}\n`;
fs.writeFileSync('lib/core/icons.dart',dart);
fs.cpSync('../ui/public/svgs/variants','assets/cards/variants',{recursive:true});
fs.copyFileSync('../ui/public/svgs/card-back-red.svg','assets/cards/back.svg');
console.log(`${icons.length} Lucide icons and web card decks synchronized.`);
